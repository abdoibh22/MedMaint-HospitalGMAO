-- ============================================================
-- MedMaint — Schéma de base de données (H2)
-- GMAO hospitalier — maintenance des équipements biomédicaux
-- Exécuté de façon idempotente par SchemaMigrator.
-- ============================================================

-- ---------- Paramètres système ----------
CREATE TABLE IF NOT EXISTS settings (
  setting_key   VARCHAR(80) PRIMARY KEY,
  setting_value VARCHAR(2000),
  updated_at    TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
  updated_by    BIGINT
);

-- ---------- Rôles et permissions ----------
CREATE TABLE IF NOT EXISTS roles (
  id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  code        VARCHAR(40) NOT NULL,
  name        VARCHAR(80) NOT NULL,
  description VARCHAR(400),
  CONSTRAINT uq_roles_code UNIQUE (code)
);

CREATE TABLE IF NOT EXISTS permissions (
  id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  code        VARCHAR(60) NOT NULL,
  description VARCHAR(200),
  CONSTRAINT uq_permissions_code UNIQUE (code)
);

CREATE TABLE IF NOT EXISTS role_permissions (
  role_id       BIGINT NOT NULL,
  permission_id BIGINT NOT NULL,
  PRIMARY KEY (role_id, permission_id),
  CONSTRAINT fk_rp_role FOREIGN KEY (role_id) REFERENCES roles(id) ON DELETE CASCADE,
  CONSTRAINT fk_rp_perm FOREIGN KEY (permission_id) REFERENCES permissions(id) ON DELETE CASCADE
);

-- ---------- Services hospitaliers ----------
CREATE TABLE IF NOT EXISTS departments (
  id        BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  code      VARCHAR(20) NOT NULL,
  name      VARCHAR(120) NOT NULL,
  head_name VARCHAR(120),
  location  VARCHAR(160),
  phone     VARCHAR(40),
  email     VARCHAR(120),
  created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT uq_departments_code UNIQUE (code)
);

-- ---------- Localisations ----------
CREATE TABLE IF NOT EXISTS locations (
  id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  department_id BIGINT NOT NULL,
  code          VARCHAR(30) NOT NULL,
  name          VARCHAR(120) NOT NULL,
  floor         VARCHAR(40),
  CONSTRAINT uq_locations_code UNIQUE (code),
  CONSTRAINT fk_loc_dept FOREIGN KEY (department_id) REFERENCES departments(id) ON DELETE CASCADE
);

-- ---------- Catégories d'équipements ----------
CREATE TABLE IF NOT EXISTS equipment_categories (
  id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  code              VARCHAR(30) NOT NULL,
  name              VARCHAR(120) NOT NULL,
  description       VARCHAR(400),
  default_frequency VARCHAR(20),
  created_at        TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT uq_categories_code UNIQUE (code)
);

-- ---------- Fabricants ----------
CREATE TABLE IF NOT EXISTS manufacturers (
  id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name       VARCHAR(120) NOT NULL,
  country    VARCHAR(80),
  website    VARCHAR(160),
  support_email VARCHAR(120),
  CONSTRAINT uq_manufacturers_name UNIQUE (name)
);

-- ---------- Fournisseurs ----------
CREATE TABLE IF NOT EXISTS suppliers (
  id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  company        VARCHAR(160) NOT NULL,
  contact_person VARCHAR(120),
  address        VARCHAR(240),
  phone          VARCHAR(40),
  email          VARCHAR(120),
  website        VARCHAR(160),
  category       VARCHAR(80),
  products       VARCHAR(400),
  contract_status VARCHAR(30) DEFAULT 'ACTIF',
  notes          VARCHAR(1000),
  archived       BOOLEAN DEFAULT FALSE,
  created_at     TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT uq_suppliers_company UNIQUE (company)
);

-- ---------- Utilisateurs ----------
CREATE TABLE IF NOT EXISTS users (
  id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  username       VARCHAR(80) NOT NULL,
  email          VARCHAR(160) NOT NULL,
  password_hash  VARCHAR(300) NOT NULL,
  full_name      VARCHAR(120) NOT NULL,
  role           VARCHAR(40) NOT NULL,
  department_id  BIGINT,
  phone          VARCHAR(40),
  status         VARCHAR(20) DEFAULT 'ACTIF',
  is_demo        BOOLEAN DEFAULT FALSE,
  notification_prefs VARCHAR(400) DEFAULT 'ALL',
  last_login     TIMESTAMP,
  created_at     TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
  updated_at     TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT uq_users_username UNIQUE (username),
  CONSTRAINT uq_users_email UNIQUE (email),
  CONSTRAINT fk_users_dept FOREIGN KEY (department_id) REFERENCES departments(id)
);

-- ---------- Techniciens ----------
CREATE TABLE IF NOT EXISTS technicians (
  id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id       BIGINT,
  employee_no   VARCHAR(40) NOT NULL,
  full_name     VARCHAR(120) NOT NULL,
  department_id BIGINT,
  specialty     VARCHAR(120),
  phone         VARCHAR(40),
  email         VARCHAR(160),
  certifications VARCHAR(600),
  status        VARCHAR(30) DEFAULT 'ACTIF',
  availability   VARCHAR(30) DEFAULT 'DISPONIBLE',
  created_at    TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT uq_technicians_empno UNIQUE (employee_no),
  CONSTRAINT fk_tech_user FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE SET NULL,
  CONSTRAINT fk_tech_dept FOREIGN KEY (department_id) REFERENCES departments(id)
);

CREATE TABLE IF NOT EXISTS technician_skills (
  id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  technician_id BIGINT NOT NULL,
  skill         VARCHAR(120) NOT NULL,
  level         VARCHAR(30) DEFAULT 'INTERMEDIAIRE',
  CONSTRAINT fk_skill_tech FOREIGN KEY (technician_id) REFERENCES technicians(id) ON DELETE CASCADE
);

-- ---------- Contrats ----------
CREATE TABLE IF NOT EXISTS contracts (
  id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  contract_no    VARCHAR(40) NOT NULL,
  supplier_id    BIGINT,
  title          VARCHAR(200) NOT NULL,
  contract_type  VARCHAR(60),
  start_date     DATE NOT NULL,
  end_date       DATE NOT NULL,
  annual_cost    DECIMAL(14,2) DEFAULT 0,
  sla            VARCHAR(400),
  response_time  VARCHAR(80),
  contact_name   VARCHAR(120),
  contact_phone  VARCHAR(40),
  contact_email  VARCHAR(120),
  status         VARCHAR(30) DEFAULT 'ACTIF',
  notes          VARCHAR(1000),
  created_at     TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT uq_contracts_no UNIQUE (contract_no),
  CONSTRAINT fk_contract_supplier FOREIGN KEY (supplier_id) REFERENCES suppliers(id)
);

-- ---------- Équipements ----------
CREATE TABLE IF NOT EXISTS equipment (
  id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  code           VARCHAR(40) NOT NULL,
  name           VARCHAR(160) NOT NULL,
  category_id    BIGINT NOT NULL,
  subcategory    VARCHAR(80),
  manufacturer_id BIGINT,
  model          VARCHAR(100),
  serial_number  VARCHAR(80),
  reference_number VARCHAR(80),
  equipment_type VARCHAR(60),
  criticality    VARCHAR(20) DEFAULT 'MOYENNE',
  risk_level     VARCHAR(20) DEFAULT 'MOYEN',
  device_class   VARCHAR(20),
  status         VARCHAR(30) DEFAULT 'EN_SERVICE',
  department_id  BIGINT NOT NULL,
  location_id    BIGINT,
  location_details VARCHAR(160),
  supplier_id    BIGINT,
  purchase_date  DATE,
  reception_date DATE,
  commissioning_date DATE,
  purchase_price DECIMAL(14,2),
  warranty_months INT,
  warranty_end_date DATE,
  maintenance_type VARCHAR(30) DEFAULT 'PREVENTIVE',
  pm_frequency   VARCHAR(20),
  last_maintenance_date DATE,
  next_maintenance_date DATE,
  responsible_id BIGINT,
  contract_id    BIGINT,
  power_supply   VARCHAR(80),
  power_rating   VARCHAR(60),
  dimensions     VARCHAR(80),
  weight_kg      DECIMAL(8,2),
  fabrication_year INT,
  notes          VARCHAR(2000),
  archived       BOOLEAN DEFAULT FALSE,
  created_by     BIGINT,
  created_at     TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
  updated_at     TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT uq_equipment_code UNIQUE (code),
  CONSTRAINT uq_equipment_serial UNIQUE (serial_number),
  CONSTRAINT fk_eq_cat FOREIGN KEY (category_id) REFERENCES equipment_categories(id),
  CONSTRAINT fk_eq_mfr FOREIGN KEY (manufacturer_id) REFERENCES manufacturers(id),
  CONSTRAINT fk_eq_dept FOREIGN KEY (department_id) REFERENCES departments(id),
  CONSTRAINT fk_eq_loc FOREIGN KEY (location_id) REFERENCES locations(id),
  CONSTRAINT fk_eq_supplier FOREIGN KEY (supplier_id) REFERENCES suppliers(id),
  CONSTRAINT fk_eq_contract FOREIGN KEY (contract_id) REFERENCES contracts(id),
  CONSTRAINT fk_eq_resp FOREIGN KEY (responsible_id) REFERENCES users(id)
);

CREATE INDEX IF NOT EXISTS idx_equipment_dept ON equipment(department_id);
CREATE INDEX IF NOT EXISTS idx_equipment_status ON equipment(status);
CREATE INDEX IF NOT EXISTS idx_equipment_cat ON equipment(category_id);

-- ---------- Checklists ----------
CREATE TABLE IF NOT EXISTS maintenance_checklists (
  id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name        VARCHAR(160) NOT NULL,
  category_id BIGINT,
  description VARCHAR(600),
  created_at  TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT fk_chk_cat FOREIGN KEY (category_id) REFERENCES equipment_categories(id)
);

CREATE TABLE IF NOT EXISTS checklist_items (
  id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  checklist_id BIGINT NOT NULL,
  position    INT NOT NULL,
  label       VARCHAR(200) NOT NULL,
  hint        VARCHAR(400),
  CONSTRAINT fk_item_chk FOREIGN KEY (checklist_id) REFERENCES maintenance_checklists(id) ON DELETE CASCADE
);

-- ---------- Plans de maintenance préventive ----------
CREATE TABLE IF NOT EXISTS maintenance_plans (
  id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  equipment_id  BIGINT NOT NULL,
  maintenance_type VARCHAR(80) NOT NULL,
  frequency     VARCHAR(20) NOT NULL,
  custom_days   INT,
  checklist_id  BIGINT,
  responsible_id BIGINT,
  last_performed DATE,
  next_due      DATE NOT NULL,
  estimated_duration_min INT,
  required_parts VARCHAR(600),
  required_tools VARCHAR(400),
  instructions  VARCHAR(2000),
  status        VARCHAR(30) DEFAULT 'A_VENIR',
  active        BOOLEAN DEFAULT TRUE,
  created_at    TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
  updated_at    TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT fk_plan_eq FOREIGN KEY (equipment_id) REFERENCES equipment(id) ON DELETE CASCADE,
  CONSTRAINT fk_plan_chk FOREIGN KEY (checklist_id) REFERENCES maintenance_checklists(id),
  CONSTRAINT fk_plan_resp FOREIGN KEY (responsible_id) REFERENCES technicians(id)
);

CREATE INDEX IF NOT EXISTS idx_plans_due ON maintenance_plans(next_due);

-- ---------- Demandes d'intervention ----------
CREATE TABLE IF NOT EXISTS intervention_requests (
  id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  request_no     VARCHAR(30) NOT NULL,
  equipment_id   BIGINT NOT NULL,
  department_id  BIGINT NOT NULL,
  requester_id   BIGINT NOT NULL,
  reported_at    TIMESTAMP NOT NULL,
  problem_description VARCHAR(4000) NOT NULL,
  symptoms       VARCHAR(1000),
  priority       VARCHAR(20) NOT NULL,
  safety_impact  BOOLEAN DEFAULT FALSE,
  availability   VARCHAR(30) DEFAULT 'INDISPONIBLE',
  status         VARCHAR(30) DEFAULT 'NOUVELLE',
  assigned_technician_id BIGINT,
  rejection_reason VARCHAR(500),
  resolution_note VARCHAR(1000),
  created_at     TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
  updated_at     TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT uq_requests_no UNIQUE (request_no),
  CONSTRAINT fk_req_eq FOREIGN KEY (equipment_id) REFERENCES equipment(id),
  CONSTRAINT fk_req_dept FOREIGN KEY (department_id) REFERENCES departments(id),
  CONSTRAINT fk_req_user FOREIGN KEY (requester_id) REFERENCES users(id),
  CONSTRAINT fk_req_tech FOREIGN KEY (assigned_technician_id) REFERENCES technicians(id)
);

CREATE INDEX IF NOT EXISTS idx_requests_status ON intervention_requests(status);
CREATE INDEX IF NOT EXISTS idx_requests_eq ON intervention_requests(equipment_id);

-- ---------- Ordres de travail / Interventions ----------
CREATE TABLE IF NOT EXISTS work_orders (
  id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  wo_no         VARCHAR(30) NOT NULL,
  request_id    BIGINT,
  equipment_id  BIGINT NOT NULL,
  technician_id BIGINT,
  team          VARCHAR(80),
  priority      VARCHAR(20) NOT NULL,
  status        VARCHAR(30) DEFAULT 'DEMANDE',
  opened_at     TIMESTAMP NOT NULL,
  scheduled_at  TIMESTAMP,
  started_at    TIMESTAMP,
  completed_at  TIMESTAMP,
  validated_at  TIMESTAMP,
  closed_at     TIMESTAMP,
  diagnosis     VARCHAR(4000),
  failure_cause VARCHAR(2000),
  corrective_action VARCHAR(2000),
  work_performed VARCHAR(4000),
  failure_type  VARCHAR(80),
  labor_hours   DECIMAL(6,2),
  downtime_hours DECIMAL(6,2),
  labor_cost    DECIMAL(14,2) DEFAULT 0,
  parts_cost    DECIMAL(14,2) DEFAULT 0,
  total_cost    DECIMAL(14,2) DEFAULT 0,
  comments      VARCHAR(2000),
  created_by    BIGINT,
  validated_by  BIGINT,
  created_at    TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
  updated_at    TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT uq_wo_no UNIQUE (wo_no),
  CONSTRAINT fk_wo_req FOREIGN KEY (request_id) REFERENCES intervention_requests(id),
  CONSTRAINT fk_wo_eq FOREIGN KEY (equipment_id) REFERENCES equipment(id),
  CONSTRAINT fk_wo_tech FOREIGN KEY (technician_id) REFERENCES technicians(id),
  CONSTRAINT fk_wo_creator FOREIGN KEY (created_by) REFERENCES users(id),
  CONSTRAINT fk_wo_validator FOREIGN KEY (validated_by) REFERENCES users(id)
);

CREATE INDEX IF NOT EXISTS idx_wo_status ON work_orders(status);
CREATE INDEX IF NOT EXISTS idx_wo_tech ON work_orders(technician_id);
CREATE INDEX IF NOT EXISTS idx_wo_eq ON work_orders(equipment_id);
CREATE INDEX IF NOT EXISTS idx_wo_opened ON work_orders(opened_at);

-- ---------- Historique maintenance / checklists complétées ----------
CREATE TABLE IF NOT EXISTS maintenance_records (
  id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  equipment_id  BIGINT NOT NULL,
  plan_id       BIGINT,
  work_order_id BIGINT,
  checklist_id  BIGINT,
  record_type   VARCHAR(30) NOT NULL,
  performed_by  BIGINT,
  performed_at  TIMESTAMP NOT NULL,
  result        VARCHAR(30) DEFAULT 'CONFORME',
  observations  VARCHAR(4000),
  duration_min  INT,
  cost          DECIMAL(14,2) DEFAULT 0,
  created_at    TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT fk_rec_eq FOREIGN KEY (equipment_id) REFERENCES equipment(id) ON DELETE CASCADE,
  CONSTRAINT fk_rec_plan FOREIGN KEY (plan_id) REFERENCES maintenance_plans(id) ON DELETE SET NULL,
  CONSTRAINT fk_rec_wo FOREIGN KEY (work_order_id) REFERENCES work_orders(id) ON DELETE SET NULL,
  CONSTRAINT fk_rec_chk FOREIGN KEY (checklist_id) REFERENCES maintenance_checklists(id),
  CONSTRAINT fk_rec_user FOREIGN KEY (performed_by) REFERENCES users(id)
);

CREATE INDEX IF NOT EXISTS idx_records_eq ON maintenance_records(equipment_id);
CREATE INDEX IF NOT EXISTS idx_records_at ON maintenance_records(performed_at);

CREATE TABLE IF NOT EXISTS checklist_results (
  id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  record_id  BIGINT NOT NULL,
  item_id    BIGINT NOT NULL,
  item_label VARCHAR(200) NOT NULL,
  result     VARCHAR(20) NOT NULL,
  notes      VARCHAR(400),
  CONSTRAINT fk_res_rec FOREIGN KEY (record_id) REFERENCES maintenance_records(id) ON DELETE CASCADE
);

-- ---------- Pièces de rechange ----------
CREATE TABLE IF NOT EXISTS spare_parts (
  id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  part_no        VARCHAR(60) NOT NULL,
  name           VARCHAR(200) NOT NULL,
  category       VARCHAR(80),
  manufacturer   VARCHAR(120),
  compatible_equipment VARCHAR(300),
  quantity       INT NOT NULL DEFAULT 0,
  min_quantity   INT DEFAULT 0,
  max_quantity   INT DEFAULT 0,
  unit_cost      DECIMAL(12,2) DEFAULT 0,
  supplier_id    BIGINT,
  storage_location VARCHAR(120),
  expiry_date    DATE,
  archived       BOOLEAN DEFAULT FALSE,
  created_at     TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
  updated_at     TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT uq_parts_no UNIQUE (part_no),
  CONSTRAINT fk_part_supplier FOREIGN KEY (supplier_id) REFERENCES suppliers(id),
  CONSTRAINT chk_part_qty CHECK (quantity >= 0 OR quantity IS NULL)
);

CREATE TABLE IF NOT EXISTS stock_transactions (
  id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  part_id      BIGINT NOT NULL,
  tx_type      VARCHAR(30) NOT NULL,
  quantity     INT NOT NULL,
  unit_cost    DECIMAL(12,2) DEFAULT 0,
  work_order_id BIGINT,
  equipment_id BIGINT,
  user_id      BIGINT,
  note         VARCHAR(400),
  created_at   TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT fk_tx_part FOREIGN KEY (part_id) REFERENCES spare_parts(id),
  CONSTRAINT fk_tx_wo FOREIGN KEY (work_order_id) REFERENCES work_orders(id) ON DELETE SET NULL,
  CONSTRAINT fk_tx_eq FOREIGN KEY (equipment_id) REFERENCES equipment(id),
  CONSTRAINT fk_tx_user FOREIGN KEY (user_id) REFERENCES users(id)
);

CREATE INDEX IF NOT EXISTS idx_tx_part ON stock_transactions(part_id);
CREATE INDEX IF NOT EXISTS idx_tx_wo ON stock_transactions(work_order_id);

CREATE TABLE IF NOT EXISTS contract_equipment (
  contract_id BIGINT NOT NULL,
  equipment_id BIGINT NOT NULL,
  PRIMARY KEY (contract_id, equipment_id),
  CONSTRAINT fk_ce_contract FOREIGN KEY (contract_id) REFERENCES contracts(id) ON DELETE CASCADE,
  CONSTRAINT fk_ce_eq FOREIGN KEY (equipment_id) REFERENCES equipment(id) ON DELETE CASCADE
);

-- ---------- Documents ----------
CREATE TABLE IF NOT EXISTS documents (
  id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  entity_type  VARCHAR(40) NOT NULL,
  entity_id    BIGINT NOT NULL,
  filename     VARCHAR(240) NOT NULL,
  stored_name  VARCHAR(240) NOT NULL,
  mime_type    VARCHAR(100),
  category     VARCHAR(80),
  size_bytes   BIGINT DEFAULT 0,
  uploaded_by  BIGINT,
  uploaded_at  TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
  description  VARCHAR(400),
  CONSTRAINT fk_doc_user FOREIGN KEY (uploaded_by) REFERENCES users(id)
);

CREATE INDEX IF NOT EXISTS idx_docs_entity ON documents(entity_type, entity_id);

-- ---------- Notifications ----------
CREATE TABLE IF NOT EXISTS notifications (
  id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id     BIGINT,
  role_code   VARCHAR(40),
  type        VARCHAR(40) NOT NULL,
  title       VARCHAR(200) NOT NULL,
  message     VARCHAR(600),
  severity    VARCHAR(20) DEFAULT 'INFO',
  entity_type VARCHAR(40),
  entity_id   BIGINT,
  is_read     BOOLEAN DEFAULT FALSE,
  created_at  TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT fk_notif_user FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE
);

CREATE INDEX IF NOT EXISTS idx_notif_user ON notifications(user_id, is_read);

-- ---------- Journal d'audit ----------
CREATE TABLE IF NOT EXISTS audit_logs (
  id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id     BIGINT,
  user_name   VARCHAR(120),
  action      VARCHAR(60) NOT NULL,
  entity_type VARCHAR(60) NOT NULL,
  entity_id   VARCHAR(60),
  entity_label VARCHAR(200),
  old_value   VARCHAR(2000),
  new_value   VARCHAR(2000),
  created_at  TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT fk_audit_user FOREIGN KEY (user_id) REFERENCES users(id)
);

CREATE INDEX IF NOT EXISTS idx_audit_at ON audit_logs(created_at);
CREATE INDEX IF NOT EXISTS idx_audit_entity ON audit_logs(entity_type, entity_id);
